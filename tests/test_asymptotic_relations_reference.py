def _conditional(value, condition):
    return ConditionalExpression(value, condition)


def test_reference_symbolic_constant_multiple_strata():
    reciprocal = sp.Pow(a, -1, evaluate=False)
    expected = (
        _conditional(True, sp.Eq(a, 0, evaluate=False)),
        _conditional(True, sp.Eq(reciprocal, 0, evaluate=False)),
        _conditional(True, sp.Ne(reciprocal, 0, evaluate=False)),
        _conditional(True, sp.Ne(a, 0, evaluate=False)),
        _conditional(True, sp.Ne(a, 0, evaluate=False)),
        _conditional(True, sp.Eq(a, 1, evaluate=False)),
    ) * 3
    assert _relation_vector(a * n**k, n**k) == expected


def test_reference_shifted_power_positive_stratum():
    expected = (
        False,
        False,
        True,
        True,
        True,
        True,
        False,
        True,
        False,
        True,
        False,
        False,
        False,
        False,
        True,
        True,
        True,
        _conditional(True, sp.Eq((1 + a) ** b, 1)),
    )
    assert (
        _relation_vector((a + n) ** b, n**b, assumptions=sp.And(a > 0, b > 0))
        == expected
    )


def test_reference_log_vs_symbolic_power_stratum():
    expected = (
        _conditional(True, p > 0),
        _conditional(False, p > 0),
        _conditional(True, p > 0),
        _conditional(False, p > 0),
        _conditional(False, p > 0),
        _conditional(False, p > 0),
        _conditional(False, p > 0),
        _conditional(True, p > 0),
        _conditional(False, p > 0),
        _conditional(True, sp.re(p) > 0),
        _conditional(False, p > 0),
        _conditional(False, p > 0),
        True,
        False,
        True,
        False,
        False,
        False,
    )
    assert _relation_vector(sp.log(n), n**p) == expected
